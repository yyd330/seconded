  function detectLang() {
    let s = null;
    try { s = localStorage.getItem("ma_lang"); } catch (e) {}
    if (s && I18N[s]) return s;
    const cands = navigator.languages || [navigator.language || "en"];
    for (const c of cands) {
      const l = String(c).toLowerCase();
      if (l.startsWith("zh")) {
        if (/(tw|hk|mo|hant)/.test(l)) return "zh-TW";
        return "zh";
      }
      if (l.startsWith("es")) return "es";
      if (l.startsWith("en")) return "en";
    }
    return "en";
  }

  const lang = detectLang();

  function T(key, vars) {
    let s = (I18N[lang] && I18N[lang][key] != null) ? I18N[lang][key]
          : (I18N.en[key] != null ? I18N.en[key] : key);
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  }

  function Tstatus(msg) {
    const m = String(msg || "");
    for (const [re, t] of STATUS_PATTERNS) {
      const g = m.match(re);
      if (g) {
        let s = t[lang] != null ? t[lang] : t.en;
        if (g[1] != null) s = s.split("$1").join(g[1]);
        return s;
      }
    }
    return m;
  }

  function Ttpl(id, fallback) {
    const k = "tpl_" + id;
    const s = (I18N[lang] && I18N[lang][k] != null) ? I18N[lang][k]
            : (I18N.en[k] != null ? I18N.en[k] : null);
    return s != null ? s : (fallback != null ? fallback : id);
  }

  function applyI18n() {
    document.documentElement.lang = lang === "zh-TW" ? "zh-Hant" : lang;
    document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = T(el.getAttribute("data-i18n")); });
    document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = T(el.getAttribute("data-i18n-html")); });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = T(el.getAttribute("data-i18n-ph")); });
    document.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = T(el.getAttribute("data-i18n-title")); });
  }

  function initLangSelect() {
    const sel = document.getElementById("langsel");
    if (!sel) return;
    sel.innerHTML = "";
    for (const code of ["en", "zh", "zh-TW", "es"]) {
      const o = document.createElement("option");
      o.value = code; o.textContent = I18N[code]._name;
      if (code === lang) o.selected = true;
      sel.appendChild(o);
    }
    sel.onchange = () => {
      try { localStorage.setItem("ma_lang", sel.value); } catch (e) {}
      location.reload();
    };
  }

  window.I18N = { lang, T, Tstatus, Ttpl, applyI18n, initLangSelect };
